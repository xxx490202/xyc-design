#!/usr/bin/env python3
"""Regenerate worker/rules.js from the Python snapshot builder.

The Python builder and the Worker must classify places and topics the same way,
so the Worker imports a JSON copy of the same tables instead of keeping a second
hand-written list.

    python3 tools/gen_worker_rules.py
"""

import ast
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools/build_monitor_data.py"
TARGET = ROOT / "worker/rules.js"
WANTED = {
    "PLATFORMS", "CATEGORIES_EN", "PROVINCES", "PROVINCE_ALIASES",
    "COUNTRIES", "CATEGORIES", "PROVINCE_EN", "EXTRA_WORDS",
}


def main():
    tree = ast.parse(SOURCE.read_text(encoding="utf-8"))
    found = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in WANTED:
                    found[target.id] = ast.literal_eval(node.value)
    missing = WANTED - set(found)
    if missing:
        raise SystemExit(f"missing in {SOURCE}: {sorted(missing)}")
    body = json.dumps(found, ensure_ascii=False, separators=(",", ":"))
    TARGET.write_text(
        "/* generated by tools/gen_worker_rules.py — do not edit by hand */\n"
        "export const RULES = " + body + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {TARGET} ({TARGET.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
